function tr(language, source) {
    var http = /^Refresh failed \(HTTP (\d+)\)$/.exec(source);
    if (http) return tr(language, 'Refresh failed (HTTP %1)', http[1]);
    var result = language === 'fa' && persian[source] !== undefined ? persian[source] : source;
    for (var i=2; i<arguments.length; i++) result = result.split('%'+(i-1)).join(Locale.digits(arguments[i], language));
    return result;
}
